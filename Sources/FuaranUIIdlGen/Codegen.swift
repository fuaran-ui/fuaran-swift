// This surface's own generator over the wire corpus's published `idl.json`
// (Phase 2299). It writes `Sources/FuaranUI/Model.generated.swift`: the sealed
// tree model of the render projection — the bare-string enums, the tagged
// unions, the records, one spec per node kind, the node-kind set and its
// categories — so a kind, case or field added to the vocabulary reaches this
// surface by regeneration and becomes a BUILD ERROR at every exhaustive
// `switch` over the model until someone writes the arm.
//
// Reading a language-neutral data artefact with this repository's own small
// generator is not a transpile: nothing here is shared with, generated by, or a
// target of any other tier, and the IDL carries no Swift. Decode policy,
// leniency, refusal wording, limits, the JSON reader, rendering and the C-ABI
// session stay hand-written, and so do the few types whose Swift representation
// is not a function of the IDL type (`Dialect.swift`, `handWritten`).
//
// THE RULES — uniform; everything they do not produce is a `Dialect.swift` entry.
//
// - Names. A kind's spec is `<Tag>Spec`; a record, union or enum keeps its IDL
//   name. A node kind's case, a union case and an enum case are the lower-camel
//   form of the tag (of the IDL `hostCases` spelling where an enum's wire token
//   is not a case name); a field keeps its IDL name. A Swift keyword is escaped
//   with backticks.
// - Types. `str` String · `int` Int · `float` Double · `bool` Bool · `json` JSON ·
//   `node` Node · list `[T]` · map `[String: T]` · enum, record and union by name.
//   `Binding`'s type argument is erased (the projection's binding is untyped; a
//   static payload is a `StaticValue`), so a type variable is a `StaticValue`. A
//   host-declared type is its declared wire type, or `JSON` when that is open.
//   A closure slot is presence-only: `Closure`.
// - Optionality. required → `T`; optional → `T?`; omit-at-default → `T` with the
//   declared default as the property's initial value where it is a literal (a
//   bool, number, string, enum case, empty list or payload-less union case; a
//   structured default is the decoder's to apply); host-only → not modelled. A
//   REQUIRED closure slot is not modelled either: it is always present and so
//   carries nothing.
// - Order. IDL declaration order.
// - Union payloads are labelled; a case whose one field is `value` is positional.
// - `NodeKind` is `indirect` (it is what keeps a value graph holding `Node`
//   finite); a union is `indirect` when it reaches itself through inline slots.
// - Emission. What the node kinds and the hand-written node envelope reach
//   through modelled fields — an IDL type nothing modelled reaches is not emitted.
// - Every field of a kind or a record is modelled (Phase 2331): the dialect may
//   leave out only a member of a union case's payload. A field the IDL gains is
//   therefore carried by regeneration, never dropped.
// - Tag sets. Every IDL union, hand-written or not, also gets `<Name>Tag`, its
//   closed `$type` set, which the decoder's dispatch switches over exhaustively.

import Foundation

public enum IdlCodegen {
  /// The generated file, relative to the package root.
  public static let generatedRelativePath = "Sources/FuaranUI/Model.generated.swift"

  /// The command that rewrites the generated file from the corpus `idl.json`.
  public static let regenerateCommand =
    "FUARAN_IDL_REGENERATE=1 swift test --filter GeneratedModelTests"

  /// The generated model for `idl` (the exact bytes of `idl.json`), or the
  /// refusal naming why it cannot be generated.
  public static func generate(idl bytes: Data) throws -> String {
    try generate(idl: bytes, dialect: dialect)
  }

  /// The generated model under `entries` in place of this surface's dialect — the
  /// seam the generator's own refusal tests drive.
  static func generate(idl bytes: Data, dialect entries: [DialectEntry]) throws -> String {
    var g = Generator(idl: try IdlReader.read(bytes), entries: entries)
    return try g.emit(idlSha256: Sha256.hex(bytes))
  }

  /// The SHA-256 the generated file records for `idl`.
  public static func sha256(_ bytes: Data) -> String { Sha256.hex(bytes) }
}

// ── The generator ──────────────────────────────────────────────────────────

private let swiftKeywords: Set<String> = [
  "associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func", "import",
  "init", "inout", "internal", "let", "open", "operator", "private", "precedencegroup",
  "protocol", "public", "rethrows", "static", "struct", "subscript", "typealias", "var",
  "break", "case", "catch", "continue", "default", "defer", "do", "else", "fallthrough", "for",
  "guard", "if", "in", "repeat", "return", "throw", "switch", "where", "while", "Any", "as",
  "await", "false", "is", "nil", "self", "Self", "super", "throws", "true", "try", "lazy",
]

private func escaped(_ ident: String) -> String {
  swiftKeywords.contains(ident) ? "`\(ident)`" : ident
}

private func lowerCamel(_ s: String) -> String {
  guard let first = s.first else { return s }
  return first.lowercased() + s.dropFirst()
}

/// One field as this surface models it.
private struct Modelled {
  let idlName: String
  let ident: String
  let type: String
  let defaultExpr: String?
  let address: String
}

private struct Generator {
  let idl: Idl
  /// The dialect this generation applies.
  let entries: [DialectEntry]
  /// Dialect entries by `<rule>|<address>`.
  var index: [String: Int] = [:]
  var used = Set<Int>()
  var usedInit = Set<String>()
  var usedDocs = Set<String>()
  let inits: [String: String]

  init(idl: Idl, entries: [DialectEntry]) {
    self.idl = idl
    self.entries = entries
    var inits: [String: String] = [:]
    for (addr, reason) in publicInitialisers { inits[addr] = reason }
    self.inits = inits
  }

  // ── Dialect access ───────────────────────────────────────────────────────

  static func key(_ s: DialectEntry.Subject) -> String {
    switch s {
    case .typeName(let a, _): return "typeName|\(a)"
    case .caseName(let a, _): return "caseName|\(a)"
    case .fieldName(let a, _): return "fieldName|\(a)"
    case .fieldType(let a, _): return "fieldType|\(a)"
    case .fieldDefault(let a, _): return "fieldDefault|\(a)"
    case .omit(let a): return "omit|\(a)"
    case .order(let a, _): return "order|\(a)"
    case .unlabeled(let a): return "unlabeled|\(a)"
    case .kindPayload(let a, _): return "kindPayload|\(a)"
    case .handWritten(let a): return "handWritten|\(a)"
    case .category(let c, _): return "category|\(c)"
    }
  }

  mutating func buildIndex() throws {
    for (i, e) in entries.enumerated() {
      let k = Self.key(e.subject)
      if index[k] != nil { throw IdlCodegenError("Dialect.swift: two entries for \(k)") }
      if e.reason.trimmingCharacters(in: .whitespaces).isEmpty {
        throw IdlCodegenError("Dialect.swift: the entry for \(k) states no reason")
      }
      index[k] = i
    }
  }

  mutating func take(_ rule: String, _ address: String) -> DialectEntry.Subject? {
    guard let i = index["\(rule)|\(address)"] else { return nil }
    used.insert(i)
    return entries[i].subject
  }

  func refuse(_ address: String, _ why: String) -> IdlCodegenError {
    IdlCodegenError(
      "Dialect.swift: the entry for \(address) \(why). Delete the entry, or correct it if the IDL moved."
    )
  }

  func isHand(_ address: String) -> Bool { index["handWritten|\(address)"] != nil }

  // ── Names ────────────────────────────────────────────────────────────────

  /// The IDL address of a record, union or enum name.
  func typeAddress(_ name: String) -> String? {
    if idl.record(name) != nil { return "record \(name)" }
    if idl.union(name) != nil { return "union \(name)" }
    if idl.enumeration(name) != nil { return "enum \(name)" }
    return nil
  }

  mutating func typeName(_ address: String, rule: String) throws -> String {
    if case .typeName(_, let s)? = take("typeName", address) {
      if s == rule {
        throw refuse(address, "renames it to `\(s)`, which is what the rules produce")
      }
      return s
    }
    return rule
  }

  mutating func swiftName(named name: String) throws -> String {
    guard let addr = typeAddress(name) else {
      throw IdlCodegenError("idl.json references an undeclared type '\(name)'")
    }
    return try typeName(addr, rule: name)
  }

  mutating func specName(_ kind: IdlKind) throws -> String {
    try typeName("kind \(kind.tag)", rule: kind.tag + "Spec")
  }

  mutating func caseIdent(_ address: String, ruleFrom tag: String) throws -> String {
    let rule = escaped(lowerCamel(tag))
    if case .caseName(_, let s)? = take("caseName", address) {
      if s == rule {
        throw refuse(address, "names the case `\(s)`, which is what the rules produce")
      }
      return s
    }
    return rule
  }

  mutating func enumCaseIdent(_ e: IdlEnum, wire: String) throws -> String {
    guard let i = e.cases.firstIndex(of: wire) else {
      throw IdlCodegenError("enum \(e.name): no case '\(wire)'")
    }
    return try caseIdent("enum \(e.name).\(wire)", ruleFrom: e.hostCases?[i] ?? wire)
  }

  mutating func unionCaseIdent(_ u: IdlUnion, tag: String) throws -> String {
    try caseIdent("union \(u.name).\(tag)", ruleFrom: tag)
  }

  // ── Types ────────────────────────────────────────────────────────────────

  mutating func swiftType(_ t: IdlType) throws -> String {
    switch t {
    case .str: return "String"
    case .int: return "Int"
    case .float: return "Double"
    case .bool: return "Bool"
    case .json: return "JSON"
    case .node: return "Node"
    case .kind: return "NodeKind"
    case .op: throw IdlCodegenError("a tree-op slot outside the op vocabulary")
    case .list(let x): return "[\(try swiftType(x))]"
    case .map(let x): return "[String: \(try swiftType(x))]"
    case .enumRef(let n), .record(let n), .union(let n, _): return try swiftName(named: n)
    case .typeVar: return "StaticValue"
    case .hosted(let w): return try w.map { try swiftType($0) } ?? "JSON"
    case .fn: return "Closure"
    }
  }

  mutating func literal(_ d: IdlDefault, _ t: IdlType) throws -> String? {
    switch (d, t) {
    case (.bool(let b), _): return b ? "true" : "false"
    case (.int(let n), _): return String(n)
    case (.float(let x), _): return "\(x)"
    case (.str(let s), _):
      return "\""
        + s.replacingOccurrences(of: "\\", with: "\\\\")
        .replacingOccurrences(of: "\"", with: "\\\"") + "\""
    case (.enumCase(let c), .enumRef(let name)):
      guard let e = idl.enumeration(name) else { return nil }
      return "." + (try enumCaseIdent(e, wire: c)).replacingOccurrences(of: "`", with: "")
    case (.list(let items), _) where items.isEmpty: return "[]"
    case (.unionCase(let tag, let fields), .union(let name, _)) where fields.isEmpty:
      guard let u = idl.union(name) else { return nil }
      return "." + (try unionCaseIdent(u, tag: tag)).replacingOccurrences(of: "`", with: "")
    default: return nil
    }
  }

  // ── Fields ───────────────────────────────────────────────────────────────

  /// The modelled fields of `owner` in declaration order.
  mutating func modelled(_ owner: String, _ fields: [IdlField]) throws -> [Modelled] {
    var out: [Modelled] = []
    for f in fields {
      let addr = "\(owner).\(f.name)"
      let ruleOmits: Bool = {
        if case .hostOnly = f.optionality { return true }
        if case .fn = f.type, case .required = f.optionality { return true }
        return false
      }()
      if take("omit", addr) != nil {
        if ruleOmits { throw refuse(addr, "omits a field the rules already leave unmodelled") }
        // Phase 2331 — a kind's or a record's field is ALWAYS carried: adding an
        // optional stored property is additive, so nothing justifies dropping one,
        // and a field this projection cannot yet render is a documented render
        // absence, not a model omission. Only a union case's payload member may be
        // left out, because adding one to a public enum case is a source break.
        guard owner.hasPrefix("union ") else {
          throw refuse(
            addr,
            "drops a field of a kind or a record; every such field is carried, and one this "
              + "projection does not render is declared in docs/RENDER-PROJECTION.md instead")
        }
        continue
      }
      if ruleOmits { continue }
      let ruleIdent = escaped(f.name)
      var ident = ruleIdent
      if case .fieldName(_, let s)? = take("fieldName", addr) {
        if s == ruleIdent {
          throw refuse(addr, "names the field `\(s)`, which is what the rules produce")
        }
        ident = escaped(s)
      }
      let base = try swiftType(f.type)
      var ruleType = base
      var ruleDefault: String? = nil
      switch f.optionality {
      case .optional: ruleType = base + "?"
      case .omitDefault(let d): ruleDefault = try literal(d, f.type)
      default: break
      }
      var type = ruleType
      if case .fieldType(_, let s)? = take("fieldType", addr) {
        if s == ruleType {
          throw refuse(addr, "types the field `\(s)`, which is what the rules produce")
        }
        type = s
        ruleDefault = nil
      }
      var def = ruleDefault
      if case .fieldDefault(_, let s)? = take("fieldDefault", addr) {
        if s == ruleDefault {
          throw refuse(addr, "defaults the field to `\(s)`, which is what the rules produce")
        }
        def = s
      }
      out.append(
        Modelled(idlName: f.name, ident: ident, type: type, defaultExpr: def, address: addr))
    }
    if case .order(_, let names)? = take("order", owner) {
      if names == out.map(\.idlName) {
        throw refuse(owner, "orders the fields as the IDL already declares them")
      }
      guard names.sorted() == out.map(\.idlName).sorted() else {
        throw refuse(
          owner,
          "orders \(names), but the modelled fields are \(out.map(\.idlName))")
      }
      out = names.map { n in out.first { $0.idlName == n }! }
    }
    return out
  }

  // ── Reachability ─────────────────────────────────────────────────────────

  /// IDL names (records, unions, enums) a type expression reaches.
  func names(in t: IdlType) -> [String] {
    switch t {
    case .list(let x), .map(let x): return names(in: x)
    case .enumRef(let n), .record(let n): return [n]
    case .union(let n, let args): return [n] + args.flatMap { names(in: $0) }
    case .hosted(let w): return w.map { names(in: $0) } ?? []
    default: return []
    }
  }

  /// The IDL names a Swift type written in the dialect reaches.
  func names(inSwift s: String) -> [String] {
    var out: [String] = []
    var cur = ""
    for ch in s + " " {
      if ch.isLetter || ch.isNumber {
        cur.append(ch)
      } else {
        if !cur.isEmpty {
          if let n = idlName(forSwift: cur) { out.append(n) }
          cur = ""
        }
      }
    }
    return out
  }

  func idlName(forSwift s: String) -> String? {
    for e in entries {
      if case .typeName(let a, let swift) = e.subject, swift == s, !a.hasPrefix("kind ") {
        return String(a.split(separator: " ", maxSplits: 1)[1])
      }
    }
    return typeAddress(s) != nil ? s : nil
  }

  mutating func fieldsOf(_ address: String) -> [IdlField] {
    let parts = address.split(separator: " ", maxSplits: 1).map(String.init)
    let rest = parts[1].split(separator: ".").map(String.init)
    switch parts[0] {
    case "kind": return idl.kind(rest[0])?.fields ?? []
    case "record": return idl.record(rest[0])?.fields ?? []
    case "union":
      guard let u = idl.union(rest[0]) else { return [] }
      if rest.count > 1 { return u.cases.first { $0.tag == rest[1] }?.fields ?? [] }
      return []
    default: return []
    }
  }

  /// Every record, union and enum the model reaches, by IDL name.
  mutating func reachable() throws -> Set<String> {
    var seen = Set<String>()
    var queue: [String] = []
    func push(_ ns: [String]) {
      for n in ns where !seen.contains(n) {
        seen.insert(n)
        queue.append(n)
      }
    }
    // The node kinds, and the hand-written node envelope.
    for k in idl.kinds {
      for m in try modelled("kind \(k.tag)", k.fields) {
        let f = k.fields.first { $0.name == m.idlName }!
        push(isRuleType(m, f) ? names(in: f.type) : names(inSwift: m.type))
      }
    }
    for f in idl.nodeFields { push(names(in: f.type)) }
    while let n = queue.popLast() {
      if let r = idl.record(n) {
        let addr = "record \(n)"
        if isHand(addr) {
          for f in r.fields { push(names(in: f.type)) }
          continue
        }
        for m in try modelled(addr, r.fields) {
          let f = r.fields.first { $0.name == m.idlName }!
          push(isRuleType(m, f) ? names(in: f.type) : names(inSwift: m.type))
        }
      } else if let u = idl.union(n) {
        let addr = "union \(n)"
        for c in u.cases {
          if isHand(addr) {
            for f in c.fields { push(names(in: f.type)) }
            continue
          }
          for m in try modelled("\(addr).\(c.tag)", c.fields) {
            let f = c.fields.first { $0.name == m.idlName }!
            push(isRuleType(m, f) ? names(in: f.type) : names(inSwift: m.type))
          }
        }
      }
    }
    return seen
  }

  mutating func isRuleType(_ m: Modelled, _ f: IdlField) -> Bool {
    let base = (try? swiftType(f.type)) ?? ""
    return m.type == base || m.type == base + "?"
  }

  // ── Recursion ────────────────────────────────────────────────────────────

  /// The records and unions a generated type holds INLINE (not through a list,
  /// a map or `Node`).
  mutating func inlineRefs(_ m: [Modelled]) -> [String] {
    m.flatMap { f -> [String] in
      let t = f.type.hasSuffix("?") ? String(f.type.dropLast()) : f.type
      if t.hasPrefix("[") { return [] }
      return idlName(forSwift: t).map { [$0] } ?? []
    }
  }

  // ── Emission ─────────────────────────────────────────────────────────────

  mutating func emit(idlSha256: String) throws -> String {
    try buildIndex()
    let reach = try reachable()
    var o = Out()
    o.line("// SPDX-License-Identifier: Apache-2.0")
    o.line("// Copyright 2026 Diametrical Ltd.")
    o.line("//")
    o.line(
      "// GENERATED from the wire corpus's `idl.json` by `Sources/FuaranUIIdlGen` — do not edit.")
    o.line("// The rules, and the dialect this surface keeps over them, are in that directory.")
    o.line("//")
    o.line("//   idl.json sha256: \(idlSha256)")
    o.line("//")
    o.line("// Regenerate with")
    o.line("//   \(IdlCodegen.regenerateCommand)")
    o.line("// or `swift run fuaran-idl-gen`. Without the variable the same test is the drift")
    o.line("// check, red when the corpus IDL has moved and this file has not.")
    o.line("")
    o.line("import Foundation")
    o.line("")
    o.line("/// The IDL this model was generated from.")
    o.line("enum GeneratedModel {")
    o.line("  /// The SHA-256 of the `idl.json` bytes.")
    o.line("  static let idlSha256 = \"\(idlSha256)\"")
    o.line("}")

    // Bare-string enums.
    o.section("Bare-string enums: the `rawValue` is the wire spelling")
    for e in idl.enums where reach.contains(e.name) {
      let name = try typeName("enum \(e.name)", rule: e.name)
      o.blank()
      o.doc(docFor("enum \(e.name)"), indent: "")
      o.line("public enum \(name): String, CaseIterable, Equatable, Sendable {")
      for wire in e.cases {
        o.doc(docFor("enum \(e.name).\(wire)"), indent: "  ")
        o.line("  case \(try enumCaseIdent(e, wire: wire)) = \"\(wire)\"")
      }
      o.line("}")
    }

    // Unions.
    o.section("Tagged unions: one case per wire `$type`")
    var unionFields: [String: [[Modelled]]] = [:]
    for u in idl.unions where reach.contains(u.name) && !isHand("union \(u.name)") {
      unionFields[u.name] = try u.cases.map { try modelled("union \(u.name).\($0.tag)", $0.fields) }
    }
    for u in idl.unions where reach.contains(u.name) && !isHand("union \(u.name)") {
      let name = try typeName("union \(u.name)", rule: u.name)
      let indirect = reachesItself(u.name, unionFields: unionFields)
      o.blank()
      o.doc(docFor("union \(u.name)"), indent: "")
      o.line("public \(indirect ? "indirect " : "")enum \(name): Equatable, Sendable {")
      for (c, fields) in zip(u.cases, unionFields[u.name]!) {
        let addr = "union \(u.name).\(c.tag)"
        let ident = try unionCaseIdent(u, tag: c.tag)
        let ruleUnlabeled = fields.count == 1 && fields[0].idlName == "value"
        var unlabeled = ruleUnlabeled
        if take("unlabeled", addr) != nil {
          if ruleUnlabeled {
            throw refuse(addr, "makes positional a payload the rules already make positional")
          }
          unlabeled = true
        }
        o.doc(docFor(addr), indent: "  ")
        if fields.isEmpty {
          o.line("  case \(ident)")
        } else {
          let params = fields.map {
            unlabeled ? $0.type : "\($0.ident.replacingOccurrences(of: "`", with: "")): \($0.type)"
          }
          o.wrapped(prefix: "  case \(ident)(", items: params, suffix: ")")
        }
      }
      o.line("}")
    }

    // Union tag sets (Phase 2331) — for EVERY union, whether or not the model reaches
    // it by a generated type: the decoder dispatches on the wire tag either way (a
    // hand-written union such as `FragmentArg` included).
    o.section("Union tag sets: the closed `$type` set of each union")
    o.line("// The decoder dispatches on these with an exhaustive `switch`, so a case the IDL")
    o.line("// gains is a build error there until its arm is written, never a run-time refusal.")
    for u in idl.unions {
      let name = try typeName("union \(u.name)", rule: u.name) + "Tag"
      o.blank()
      o.line("/// The closed `$type` set of `\(u.name)`.")
      o.line("enum \(name): String, CaseIterable {")
      for c in u.cases {
        o.line("  case \(try unionCaseIdent(u, tag: c.tag)) = \"\(c.tag)\"")
      }
      o.line("}")
    }

    // Records.
    o.section("Records")
    for r in idl.records where reach.contains(r.name) && !isHand("record \(r.name)") {
      let addr = "record \(r.name)"
      try emitStruct(&o, addr, try typeName(addr, rule: r.name), try modelled(addr, r.fields))
    }

    // Kind specs.
    o.section("Node kind specs")
    var payloads: [String: String] = [:]
    for k in idl.kinds {
      let addr = "kind \(k.tag)"
      if case .kindPayload(_, let field)? = take("kindPayload", addr) {
        let m = try modelled(addr, k.fields)
        guard m.count == 1, m[0].idlName == field else {
          throw refuse(
            addr, "holds `\(field)` as the payload, but the modelled fields are \(m.map(\.idlName))"
          )
        }
        payloads[k.tag] = m[0].type
        continue
      }
      try emitStruct(&o, addr, try specName(k), try modelled(addr, k.fields))
    }

    // The kind set.
    var categories: [String] = []
    for k in idl.kinds where !categories.contains(k.category) { categories.append(k.category) }
    var categoryIdent: [String: String] = [:]
    for c in categories {
      let rule = lowerCamel(c)
      if case .category(_, let s)? = take("category", c) {
        if s == rule {
          throw refuse("category \(c)", "names it `\(s)`, which is what the rules produce")
        }
        categoryIdent[c] = s
      } else {
        categoryIdent[c] = rule
      }
    }
    var kindIdent: [String: String] = [:]
    for k in idl.kinds { kindIdent[k.tag] = try caseIdent("kind \(k.tag)", ruleFrom: k.tag) }

    o.section("The node kind set")
    o.blank()
    o.line("/// The behavioural category a primitive belongs to — recovered on decode, never")
    o.line("/// a wire level.")
    o.line("public enum NodeCategory: Equatable, Sendable {")
    for c in categories { o.line("  case \(categoryIdent[c]!)") }
    o.line("}")
    o.blank()
    o.line("/// The closed `kind.$type` discriminator set — one case per IDL kind. A decoder")
    o.line("/// dispatches on it with an exhaustive `switch`, so a kind added to the IDL is a")
    o.line("/// build error there until its arm is written.")
    o.line("public enum NodeKindTag: String, CaseIterable, Equatable, Sendable {")
    for k in idl.kinds { o.line("  case \(kindIdent[k.tag]!) = \"\(k.tag)\"") }
    o.blank()
    o.line("  /// The host-side behavioural classification (§3.2). Exhaustive by construction.")
    o.line("  public var category: NodeCategory {")
    o.line("    switch self {")
    for c in categories {
      let members = idl.kinds.filter { $0.category == c }.map {
        "." + kindIdent[$0.tag]!.replacingOccurrences(of: "`", with: "")
      }
      o.wrapped(prefix: "    case ", items: members, suffix: ":", indent: "      ")
      o.line("      return .\(categoryIdent[c]!)")
    }
    o.line("    }")
    o.line("  }")
    o.line("}")
    o.blank()
    o.line("/// The node's primitive kind: the closed, flat `kind.$type` vocabulary.")
    o.line("public indirect enum NodeKind: Equatable, Sendable {")
    for k in idl.kinds {
      let payload = try payloads[k.tag] ?? specName(k)
      o.line("  case \(kindIdent[k.tag]!)(\(payload))")
    }
    o.blank()
    o.line("  /// The wire discriminator of this kind. Exhaustive by construction.")
    o.line("  public var tag: NodeKindTag {")
    o.line("    switch self {")
    for k in idl.kinds {
      let id = kindIdent[k.tag]!.replacingOccurrences(of: "`", with: "")
      o.line("    case .\(id): return .\(id)")
    }
    o.line("    }")
    o.line("  }")
    o.blank()
    o.line("  /// The wire `$type` discriminator of this kind.")
    o.line("  public var typeName: String { tag.rawValue }")
    o.blank()
    o.line("  /// The host-side behavioural classification (§3.2).")
    o.line("  public var category: NodeCategory { tag.category }")
    o.line("}")

    // Everything the dialect and the construction table name must have been used.
    try checkComplete()
    return o.text
  }

  func reachesItself(_ name: String, unionFields: [String: [[Modelled]]]) -> Bool {
    var seen = Set<String>()
    var stack = [name]
    var g = self
    while let n = stack.popLast() {
      var next: [String] = []
      if let cases = unionFields[n] {
        for fields in cases { next += g.inlineRefs(fields) }
      } else if let r = idl.record(n), !isHand("record \(n)") {
        next += g.inlineRefs((try? g.modelled("record \(n)", r.fields)) ?? [])
      }
      for x in next {
        if x == name { return true }
        if !seen.contains(x) {
          seen.insert(x)
          stack.append(x)
        }
      }
    }
    return false
  }

  mutating func emitStruct(_ o: inout Out, _ addr: String, _ name: String, _ fields: [Modelled])
    throws
  {
    o.blank()
    o.doc(docFor(addr), indent: "")
    o.line("public struct \(name): Equatable, Sendable {")
    for f in fields {
      o.doc(docFor(f.address), indent: "  ")
      o.line("  public var \(f.ident): \(f.type)\(f.defaultExpr.map { " = \($0)" } ?? "")")
    }
    if inits[addr] != nil {
      usedInit.insert(addr)
      o.blank()
      let params = fields.map { f -> String in
        var p = "\(f.ident.replacingOccurrences(of: "`", with: "")): \(f.type)"
        if let d = f.defaultExpr { p += " = \(d)" } else if f.type.hasSuffix("?") { p += " = nil" }
        return p
      }
      o.wrapped(prefix: "  public init(", items: params, suffix: ") {")
      for f in fields { o.line("    self.\(f.ident) = \(f.ident)") }
      o.line("  }")
    }
    o.line("}")
  }

  mutating func docFor(_ address: String) -> [String] {
    guard let text = modelDocs[address] else { return [] }
    usedDocs.insert(address)
    return text.split(separator: "\n", omittingEmptySubsequences: false).map(String.init)
  }

  func checkComplete() throws {
    var stale: [String] = []
    for (i, e) in entries.enumerated() where !used.contains(i) && !isHandEntry(e) {
      stale.append("\(Self.key(e.subject)) (\(e.reason))")
    }
    for (addr, _) in publicInitialisers where !usedInit.contains(addr) {
      stale.append("publicInitialisers|\(addr)")
    }
    for addr in modelDocs.keys.sorted() where !usedDocs.contains(addr) {
      stale.append("modelDocs|\(addr)")
    }
    if !stale.isEmpty {
      throw IdlCodegenError(
        "the dialect names positions the generated model does not have — `idl.json` no longer "
          + "declares them, or nothing modelled reaches them. Delete or correct each:\n  "
          + stale.joined(separator: "\n  "))
    }
  }

  func isHandEntry(_ e: DialectEntry) -> Bool {
    guard case .handWritten(let a) = e.subject else { return false }
    let parts = a.split(separator: " ", maxSplits: 1).map(String.init)
    switch parts.first {
    case "record": return idl.record(parts[1]) != nil
    case "union": return idl.union(parts[1]) != nil
    default: return false
    }
  }
}

// ── Output ─────────────────────────────────────────────────────────────────

private struct Out {
  var text = ""
  static let width = 100

  mutating func line(_ s: String) { text += s + "\n" }
  mutating func blank() { text += "\n" }

  mutating func section(_ title: String) {
    blank()
    let head = "// ── \(title) "
    line(head + String(repeating: "─", count: max(3, 80 - head.count)))
  }

  mutating func doc(_ lines: [String], indent: String) {
    for l in lines { line(indent + (l.isEmpty ? "///" : "/// " + l)) }
  }

  /// `prefix` + items joined by ", " + `suffix`, wrapped at the column limit
  /// the way swift-format breaks a long parameter list: after the opening
  /// delimiter, continuation lines indented two spaces past the declaration.
  mutating func wrapped(prefix: String, items: [String], suffix: String, indent: String? = nil) {
    let one = prefix + items.joined(separator: ", ") + suffix
    if one.count <= Self.width {
      line(one)
      return
    }
    let lead = String(prefix.prefix { $0 == " " })
    let cont = indent ?? (lead + "  ")
    // A parameter list breaks after its opening delimiter; a `case` pattern list
    // fills its first line.
    let breaksAfterOpen = prefix.hasSuffix("(")
    // `) {` closes on its own line, at the declaration's indent.
    let closesAlone = suffix.hasPrefix(")") && suffix.contains("{")
    let lastSuffix = closesAlone ? "" : suffix
    var cur: String
    if breaksAfterOpen {
      line(prefix)
      cur = cont
    } else {
      cur = prefix
    }
    var fresh = true
    for (i, item) in items.enumerated() {
      let piece = item + (i == items.count - 1 ? lastSuffix : ",")
      if fresh {
        cur += piece
        fresh = false
      } else if cur.count + 1 + piece.count <= Self.width {
        cur += " " + piece
      } else {
        line(cur)
        cur = cont + piece
      }
    }
    line(cur)
    if closesAlone { line(lead + suffix) }
  }
}
